use std::io::Read;
use std::path::{Path, PathBuf};

use anyhow::Context;
use tokio::io::AsyncWriteExt;

use crate::abstraction::{Report, Snapshot, TableRef};
use crate::patched::throbberous::Throbber;

const MARKER: &str = "-- sbp clone: generated seed";

const BATCH: usize = 500;

pub struct Seed {
    path: PathBuf,
}

impl Seed {
    pub fn new(path: &Path) -> anyhow::Result<Self> {
        if let Ok(file) = std::fs::File::open(path) {
            let mut beginning = Vec::new();

            file.take(MARKER.len() as u64)
                .read_to_end(&mut beginning)
                .with_context(|| {
                    styled_error!(
                        "Couldn't read `{}`",
                        (path.display().to_string(), "file_path")
                    )
                })?;

            if beginning != MARKER.as_bytes() {
                crate::styled_bail!(
                    "`{}` already exists and wasn't generated by `{}`, move it away or pick another file",
                    (path.display().to_string(), "file_path"),
                    ("sbp clone", "command")
                );
            }
        }

        Ok(Self { path: path.into() })
    }

    pub async fn write(
        &self,
        snapshot: &Snapshot<'_>,
        throbber: Option<&Throbber>,
    ) -> anyhow::Result<Report> {
        let mut file = tokio::fs::File::create(&self.path).await.with_context(|| {
            styled_error!(
                "Couldn't create `{}`",
                (self.path.display().to_string(), "file_path")
            )
        })?;

        let mut report = Report::default();

        file.write_all(
            format!("{MARKER}\n-- Rows which already exist after migrations are skipped.\nSET session_replication_role = replica;\n\n").as_bytes(),
        )
        .await?;

        let production = snapshot.connection().client();

        for item in snapshot.items() {
            if let Some(throbber) = throbber {
                throbber
                    .set_message(format!(" copying `{}`…", item.table()))
                    .await;
            }

            production
                .execute(
                    &format!(
                        "DECLARE sbp_seed NO SCROLL CURSOR FOR {}",
                        item.insert_statements_sql()
                    ),
                    &[],
                )
                .await
                .with_context(|| {
                    styled_error!("Couldn't read `{}`", (item.table().to_string(), "id"))
                })?;

            let mut rows = 0;

            loop {
                let batch = production
                    .query(&format!("FETCH {BATCH} FROM sbp_seed"), &[])
                    .await?;

                if batch.is_empty() {
                    break;
                }

                rows += batch.len() as u64;

                for row in batch {
                    let statement: String = row.get(0);

                    file.write_all(format!("{statement}\n").as_bytes()).await?;
                }
            }

            production.execute("CLOSE sbp_seed", &[]).await?;
            report.record_table(item, rows);
        }

        let tables: Vec<TableRef> = snapshot
            .items()
            .iter()
            .map(|item| item.table().clone())
            .collect();

        file.write_all(
            format!(
                "\n{}\n\nSET session_replication_role = DEFAULT;\n",
                TableRef::reset_sequences_sql(&tables)
            )
            .as_bytes(),
        )
        .await?;

        snapshot.release().await;

        Ok(report)
    }
}
